"""Build the s8-field variant of the TidePool fixture: a router past the 200-line guidance that
carries the four shapes the HDL pilot found S8 silent on, a ROADMAP that states a halt, and a
NOTEBOOK with a graduate aimed at ARCHITECTURE.

python build_variant.py <fixture dir> <out dir>

Writes CLAUDE.md, ROADMAP.md and NOTEBOOK.md into <out dir> (overlay them on a fixture copy,
then baseline). The router: the base router, then (a) the CO-OPS pack from the fat-gotchas
variant (file-keyed, a rule file's case), (b) a build-and-bench procedure block keyed to no
file (an activity: a skill's case, or one guard line), (c) gotchas about a sibling
repository's files (no glob here can name them), (d) the base ARCHITECTURE's module map
copied verbatim (a duplicate: cross-reference and drop, never move), (e) a State block that
changes at release cadence (ROADMAP's). The ROADMAP: the base plus "Halted at v0.6". The
NOTEBOOK: the base plus the fat-arch entries (the 2026-07-08 one graduates to ARCHITECTURE).
"""
import io
import os
import sys

BUILD_BLOCK = """
## Building, flashing and the bench (read before any `make` or a bench run)

The release build is `make release` from the repo root; it runs `pytest tests/` first and
refuses to tag on a red suite, then builds the wheel into `dist/` and writes the version
from `pyproject.toml` into `src/tidepool/__init__.py`. Gotchas, every one learned on a bench
day:

- **`make release` with a dirty tree tags the wrong commit.** The Makefile reads `git
  describe` after the build, not before; commit first, then build. The 0.5.1 tag sits on
  a commit that lacks the exporter fix for this reason.
- **The bench laptop's `pip` is 3.10's.** `make release` on it builds a wheel that installs
  nowhere else (`requires-python >= 3.11` is in the metadata but the wheel tag is cp310).
  Build on the desktop or in the 3.11 venv at `~/venvs/tp311`.
- **Flashing the field tablet is `make flash TARGET=/Volumes/TIDEPOOL`;** the target must be
  the mounted volume, never a path inside it, or `rsync` creates a second copy one level
  down and the tablet runs the old one.
- **The bench run is `make bench STATION=9414290 DAYS=3`** against the live service; it
  needs the network and writes `bench/last.csv`. Never run it in a loop: each run is one
  datagetter request and the bench network shares one source address with the lab.
- **A bench run that prints "no windows" is usually the station, not the code:** run
  `tidepool tides` for the same range first; a diurnal station can have no low in three
  days. Only then suspect the threshold.
- **The XMODEM transfer to the tablet's console uses CRC, not Checksum;** Tera Term's
  default is Checksum and the transfer stalls at 1 percent with no error.
- **`make clean` removes `dist/` and `bench/`, including `bench/last.csv`;** copy the bench
  result out before cleaning, or the field comparison is lost.
- **The tablet's clock drifts about 40 s a week with no NTP on the bench network;** a
  window printed as 05:59 may be 06:00 by the station's clock. Set the clock before a
  field day.
"""

SIBLING_BLOCK = """
## The harmonics core (`../tidepool-core/`, a sibling repository this one consumes)

The offline-harmonics work lives in the sibling repository `../tidepool-core/`
(`src/tidepool_core/harmonics.py`, `constituents.csv`); this package will import it once the
offline mode lands. Its rules bind this repository's code already:

- **`harmonics.predict(constituents, t)` takes UTC, never station-local time;** every
  caller here converts with the station's zone from the metadata record, which is why the
  cache's metadata fetch must land before the offline mode does.
- **`constituents.csv` is regenerated by its own `make constituents` in that repository;**
  never edit it by hand here, and never vendor a copy: the sibling's `MANIFEST` hash is
  checked at import and a stale copy raises `ConstituentsMismatch`.
- **A change to `harmonics.py`'s datum handling is a change to this package's `GOOD_TIDE_FT`
  semantics;** the two are released together (the sibling's CHANGELOG names the pairing).
"""

STATE_BLOCK = """
## State (2026-07-10)

Version 0.6.0 is current; 0.6.1 waits for the station refresh script. Shipped since 0.5:
the export subcommand (2026-06-10), the moon-phase factor (2026-06-24), the astral sunrise
and sunset (2026-05-28), Newport and The Battery (2026-05-14). Open: confidence intervals on
the window score (design sketch in NOTEBOOK 2026-06-30); the `low_tides()` height cut (the
La Push report); the metadata cache's writer. Next release: 0.7, the offline-harmonics
mode, after `../tidepool-core/` ships its `predict`.
"""

BENCH_NET_BLOCK = """
## The bench network (every bench day, before the first run)

- **The bench NIC is fully static:** 192.168.7.1/24 on the laptop, 192.168.7.2 on the
  tablet, no gateway; never `New-NetIPAddress` on an interface that still has DHCP, or
  Windows keeps both and the tablet answers on the wrong one for a minute.
- **The lab's NOAA proxy is at 192.168.7.254 and caches predictions for 10 minutes;** a
  bench run inside that window returns the cached response, so a changed `--days` shows no
  change until the cache ages out. `tidepool tides` against the proxy shows the cache's
  timestamp header in its first line.
- **The tablet's console is COM5 at 115200 8N1;** Tera Term's "Receive: AUTO" turns a bare
  CR into a new line and makes the in-place progress redraw scroll. Set "Receive: CR".
- **A field day's CSVs go under `bench/<date>/`, never `bench/last.csv`;** `make clean`
  takes `bench/` whole (see the build block), and the dated folders are what the season's
  comparison reads.
- **The GPS on the tablet is off by default;** the planner does not use it, but the field
  notes app does, and a note stamped at 00:00 is one taken with the GPS off.
- **Leave the proxy running between days;** its first start re-fetches station metadata
  for every registry entry, which is eighteen requests at once against the live service.
"""

CONVENTIONS = """
## Conventions
- Every behavior change is an OpenSpec change here; docs ride the change's commit.
- Work lands on `dev`; `main` fast-forwards at a release; there is no remote.
- Heights in feet everywhere in the code and the docs; a datum is named wherever a height is.
"""

HALT_LINE = """- **Halted at v0.6 (2026-07-10).** No further development: the planner is frozen at this
  release for the season's field use, and only documentation and bench records change until
  the freeze lifts (a decision recorded here; see NOTEBOOK 2026-07-10).
"""


def main(fixture, out):
    base = io.open(os.path.join(fixture, 'CLAUDE.md'), encoding='utf-8', newline='').read()
    arch = io.open(os.path.join(fixture, 'ARCHITECTURE.md'), encoding='utf-8', newline='').read()
    variants = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    fat = io.open(os.path.join(variants, 'fat-gotchas', 'CLAUDE.md'), encoding='utf-8', newline='').read()
    pack = fat[fat.find('\n## Gotchas (the CO-OPS'):]
    module_map = arch[arch.find('\n## Module map'):arch.find('\n## Data flow')]
    router = (base.rstrip('\n') + '\n' + STATE_BLOCK + module_map.replace('## Module map', '## Module map (copied here for quick reference)')
              + BUILD_BLOCK + BENCH_NET_BLOCK + SIBLING_BLOCK + pack + CONVENTIONS)
    roadmap = io.open(os.path.join(fixture, 'ROADMAP.md'), encoding='utf-8', newline='').read()
    i = roadmap.find('## Now / Next\n') + len('## Now / Next\n')
    roadmap = roadmap[:i] + HALT_LINE + roadmap[i:]
    nb = io.open(os.path.join(fixture, 'NOTEBOOK.md'), encoding='utf-8', newline='').read()
    app = io.open(os.path.join(variants, 'fat-arch', 'NOTEBOOK-append.md'), encoding='utf-8', newline='').read()
    entries = ''.join(l for l in app.split('\n', 2)[2:])
    halt_entry = ("- **2026-07-10**: Decided: the planner halts at v0.6 for the field season; no feature work,\n"
                  "  no refactor, docs and bench records only, until the freeze lifts after the last field day.\n")
    j = nb.find('\n- **2026-')
    nb = nb[:j + 1] + halt_entry + entries.rstrip('\n') + '\n' + nb[j + 1:]
    os.makedirs(out, exist_ok=True)
    for name, text in (('CLAUDE.md', router), ('ROADMAP.md', roadmap), ('NOTEBOOK.md', nb)):
        io.open(os.path.join(out, name), 'w', encoding='utf-8', newline='').write(text)
        print(f'{name}: {len(text.encode()) / 1024:.1f} KB, {text.count(chr(10))} lines')


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
